@app.post('/api/inspections/batch',status_code=202)
def batch(bodies:list[InspectionInput],who:Actor=Depends(actor),idempotency_key:str|None=Header(default=None)):
    if not 1<=len(bodies)<=3:raise ValueError('每批最多三个设施任务')
