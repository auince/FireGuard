@app.post('/api/feedback/{identifier}/attribution',status_code=202)
def correct_attribution(identifier:str,body:dict,who:Actor=Depends(actor)):
    row=store.db.feedback.find_one({'_id':identifier});access(who,row,write=True)
    category=body.get('category')
    if category not in ['intent','vision','retrieval','applicability','generation','knowledge_gap']:raise ValueError('归因类别无效')
    expected=int(body.get('expected_version',1));next_version=expected+1
    reason=str(body.get('reason',row['text']))[:4000];key='attribution:'+identifier+':'+str(next_version)
    payload={'feedback_id':identifier,'project_id':row['project_id'],'attribution_version':next_version}
    request_hash=digest([category,reason])
    existing=store.db.jobs.find_one({'owner':who.user_id,'idempotency_key':key})
    if existing:
        if existing.get('attribution_request_hash')!=request_hash:raise HTTPException(409,'同版本归因修改内容冲突')
        return {'id':existing['_id'],'attribution_version':next_version}
    jid=uuid.uuid4().hex
    with store.client.start_session() as session:
        with session.start_transaction():
            selector=({'_id':identifier,'$or':[{'attribution_version':1},{'attribution_version':{'$exists':False}}]} if expected==1 else {'_id':identifier,'attribution_version':expected})
            changed=store.db.feedback.update_one(selector,{'$set':{'category':category,'text':reason,'state':'queued','candidate_id':None,'attribution_version':next_version}},session=session)
            if not changed.modified_count:raise HTTPException(409,'反馈归因版本已变化')
            if row.get('candidate_id'):
                store.db.policies.update_one({'_id':row['candidate_id'],'state':'draft'},{'$set':{'state':'deprecated','reason':'attribution_corrected'}},session=session)
            store.db.jobs.insert_one({'_id':jid,'owner':who.user_id,'project_id':row['project_id'],'kind':'feedback','input':payload,
                'input_hash':digest(payload),'attribution_request_hash':request_hash,'idempotency_key':key,'status':'queued','revision':1,'created_at':now(),'attempts':0},session=session)
            store.db.outbox.insert_one({'_id':jid+':1','job_id':jid,'sent':False,'created_at':now()},session=session)
    store.audit(identifier,'attribution:'+str(next_version),'human_attribution_correction',actor=who.user_id,previous=row.get('category'),category=category)
    return {'id':jid,'attribution_version':next_version}
