def prepare(body,who):
    if body.project_id not in who.projects:raise HTTPException(403,'项目访问被拒绝')
    req=body.model_dump(mode='json');req['session_id']=req['session_id'] or uuid.uuid4().hex
    im=req.pop('image',None)
    if im:
        if not im.startswith('data:image/'):raise ValueError('只接受上传图片')
        try:
            raw=base64.b64decode(im.split(',',1)[1],validate=True)
            image=Image.open(io.BytesIO(raw))
            if len(raw)>10*1024*1024 or image.width*image.height>16000000 or image.format not in {'JPEG','PNG'}:raise ValueError('image limits')
            image.load()
            image=image.convert('RGB');image.thumbnail((1600,1600));out=io.BytesIO();image.save(out,'JPEG',quality=92)
        except Exception as exc:raise ValueError('图片数据无效') from exc
        root=ROOT/'runtime/v2/uploads';root.mkdir(parents=True,exist_ok=True)
        original=digest(raw);processed=digest(out.getvalue())
        (root/(original+'.image')).write_bytes(raw);(root/(processed+'.jpg')).write_bytes(out.getvalue())
        req.update(image_sha256=original,processed_image_sha256=processed,original_image_path=str(root/(original+'.image')),
                   processed_image_path=str(root/(processed+'.jpg')))
    return req

def submit(body,who,key):
    req=prepare(body,who)
    # Session IDs generated by the server must not break request idempotency.
    if key and body.session_id is None:req['session_id']=digest([who.user_id,key])[:32]
    job=store.submit(body.mode,req,who,key or uuid.uuid4().hex)
    return {'id':job['_id'],'run_id':job['_id'],'status':job['status'],'revision':job['revision'],'session_id':req['session_id']}

