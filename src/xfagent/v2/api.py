@app.post('/api/auth/login')
def login(body:dict,request:Request):
    # Rate limit login without making credentials available to graph/model nodes.
    import redis
    from .config import REDIS
    r=redis.Redis.from_url(REDIS,socket_timeout=2);key='xfv2:login:'+digest([request.client.host,int(time.time()//60)])
    try:
        count=r.incr(key);r.expire(key,65)
        if count>10:raise HTTPException(429,'请稍后再试')
    except redis.RedisError:raise HTTPException(503,'登录服务暂不可用')
    user=store.db.users.find_one({'_id':str(body.get('username',''))})
    password=str(body.get('password',''))
    if not user or len(password)>256:raise HTTPException(401,'登录失败')
    value=hashlib.scrypt(password.encode(),salt=bytes.fromhex(user['salt']),n=16384,r=8,p=1).hex()
    if not secrets.compare_digest(value,user['password_hash']):raise HTTPException(401,'登录失败')
    token=jwt.encode({'sub':user['_id'],'role':user['role'],'projects':user['projects'],
        'jti':uuid.uuid4().hex,'iat':now(),'exp':now()+timedelta(hours=8),'aud':'xfagent-v2'},secret(),algorithm='HS256')
    return {'access_token':token,'role':user['role'],'projects':user['projects']}

