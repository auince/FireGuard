    result=[submit(b,who,identifier+':'+str(i)) for i,b in enumerate(bodies)]
    store.db.batches.update_one({'_id':identifier},{'$setOnInsert':{'owner':who.user_id,'project_id':bodies[0].project_id,
        'children':[x['id'] for x in result],'created_at':now()}},upsert=True)
