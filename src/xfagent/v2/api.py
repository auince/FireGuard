@app.get('/api/metrics')
def metrics():
    reg=CollectorRegistry();count=Gauge('xfagent_jobs','Jobs by status',['status'],registry=reg)
    for s in ['queued','running','awaiting_review','awaiting_information','complete','failed']:count.labels(s).set(store.db.jobs.count_documents({'status':s}))
    calls=Gauge('xfagent_model_calls_total','Recorded calls',registry=reg)
    total=list(store.db.jobs.aggregate([{'$group':{'_id':None,'n':{'$sum':'$result.calls'}}}]))
    calls.set(total[0]['n'] if total else 0)
    stage=Gauge('xfagent_stage_seconds','Recorded stage duration',['node','stat'],registry=reg)
    for row in store.db.events.aggregate([{'$match':{'event':'node_complete'}},{'$group':{'_id':'$node','mean':{'$avg':'$seconds'},'max':{'$max':'$seconds'},'count':{'$sum':1}}}]):
        for stat in ['mean','max','count']:stage.labels(row['_id'],stat).set(row[stat])
    oldest=store.db.jobs.find_one({'status':'queued'},sort=[('created_at',1)])
    age=Gauge('xfagent_queue_oldest_seconds','Oldest queued task age',registry=reg)
    age.set((now()-oldest['created_at']).total_seconds() if oldest else 0)
    TraceAggregator(store).prometheus(reg)
    return Response(generate_latest(reg),media_type=CONTENT_TYPE_LATEST)

