@app.post('/api/reports/{identifier}/review',status_code=202)
def review(identifier:str,body:Review,who:Actor=Depends(actor)):
    row=store.db.jobs.find_one({'_id':identifier});access(who,row,write=True)
    if body.action=='approve':
        state=row.get('result',{});req=dict(state.get('request',row['input']));req['scene']={**req.get('scene',{}),**body.confirmed_scene}
        checked=verify(store,{**state,'request':req},body.conclusions if body.conclusions is not None else state.get('conclusions',[]))
        if not checked['passed']:raise HTTPException(409,{'message':'请先修改未通过的结论','verification':checked})
    revision=store.enqueue_resume(row,body.model_dump(),who)
    store.audit(identifier,'review:'+str(revision),'human_review',reviewer=who.user_id,decision=body.model_dump())
    return {'id':identifier,'revision':revision,'status':'queued'}

@app.post('/api/jobs/{identifier}/resume',status_code=202)
def resume(identifier:str,who:Actor=Depends(actor)):
    row=store.db.jobs.find_one({'_id':identifier});access(who,row)
    if row['status']!='failed':raise HTTPException(409,'仅失败任务可恢复；待复核任务请提交复核')
    # Recovery continues the existing graph checkpoint, not a new human decision.
    with store.client.start_session() as s:
        with s.start_transaction():
            result=store.db.jobs.update_one({'_id':identifier,'status':'failed','revision':row['revision']},
                {'$set':{'status':'queued','resume':None},'$inc':{'revision':1}},session=s)
            if not result.modified_count:raise HTTPException(409,'任务状态已变化')
            store.db.outbox.insert_one({'_id':identifier+':'+str(row['revision']+1),'job_id':identifier,'sent':False,'created_at':now()},session=s)
    return {'id':identifier,'status':'queued'}

